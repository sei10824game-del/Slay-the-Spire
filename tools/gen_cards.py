#!/usr/bin/env python3
"""Regenerates src/main/java/com/spiremod/mobs/heroes/CardData.java from the slaythespire.wiki.gg Cargo `Cards` table.
Run after card updates:  python3 tools/gen_cards.py   (then rebuild). Needs network access to the wiki."""
import json, re, html, urllib.request, urllib.parse, pathlib

URL = "https://slaythespire.wiki.gg/api.php"
def q(offset):
    p = dict(action="cargoquery", tables="Cards", fields="Name,Color,Rarity,Type,Cost,Description,Game", format="json", limit=500, offset=offset,
             where="Type IN ('Attack','Skill','Power') AND Rarity IN ('Basic','Common','Uncommon','Rare')")
    req = urllib.request.Request(URL + "?" + urllib.parse.urlencode(p), headers={"User-Agent": "spiremod-card-sync/1.0"})
    return json.load(urllib.request.urlopen(req))["cargoquery"]

def plain(d):
    d = re.sub(r"<br\s*/?>", " ", d)
    d = re.sub(r"\[\[File:[^\]]*\]\]", "", d)
    d = re.sub(r"\[\[(?:[^\]|]*\|)?([^\]]*)\]\]", r"\1", d)
    d = re.sub(r"<[^>]+>", "", d)
    d = html.unescape(d)
    d = re.sub(r"\(([^;()]*);[^()]*\)", r"\1", d)      # (base;upgraded) -> base
    d = re.sub(r"\{\{[^{}]*\}\}", "", d)
    return re.sub(r"\s+", " ", d).strip()

rows, seen, off = [], set(), 0
while True:
    page = q(off)
    for r in page:
        t = r["title"]
        if t["Game"] not in ("1", "2") or t["Color"] == "Colorless": continue
        k = (t["Game"], t["Color"], t["Name"])
        if k in seen: continue
        seen.add(k)
        rows.append("|".join([t["Game"], t["Color"], t["Name"], t["Rarity"], t["Type"], (t["Cost"] or "1"), plain(t["Description"] or "")]))
    if len(page) < 500: break
    off += 500
rows.sort()
body = ",\n".join('        "%s"' % r.replace("\\", "\\\\").replace('"', '\\"') for r in rows)
out = pathlib.Path(__file__).resolve().parent.parent / "src/main/java/com/spiremod/mobs/heroes/CardData.java"
out.write_text("""package com.spiremod.mobs.heroes;

/** GENERATED by tools/gen_cards.py from the wiki Cards table (base, not upgraded, values). game|color|name|rarity|type|cost|text. Do not edit by hand. */
final class CardData {
    private CardData() {}
    static final String[] ROWS = {
""" + body + "\n    };\n}\n")
print(len(rows), "cards ->", out)
