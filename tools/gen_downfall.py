#!/usr/bin/env python3
"""Regenerates heroes/DownfallData.java from a checkout of the Downfall (StS1) mod source.
usage: python3 tools/gen_downfall.py /path/to/DownfallSTS
Reads each villain's card classes (cost/type/rarity/numbers) + eng CardStrings.json and writes rows
`DF|<char>|<name>|<rarity>|<type>|<cost>|<text>` (text uses the same phrasing CardMoves understands) and character rows."""
import json, re, sys, pathlib

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/home/user/DownfallSTS")
J = root / "src/main/java"; R = root / "src/main/resources"
CH = {  # char id -> (java card dir, resource dir, hp, base-class guess)
    "hexaghost": ("theHexaghost/cards", "hexamodResources", 66),
    "guardian":  ("guardian/cards", "guardianResources", 80),
    "slimebound": ("slimebound/cards", "slimeboundResources", 65),
    "champ":     ("champ/cards", "champResources", 80),
    "automaton": ("automaton/cards", "bronzeResources", 70),
    "collector": ("collector/cards", "collectorResources", 65),
    "gremlin":   ("gremlin/cards", "gremlinResources", 75),
    "snecko":    ("sneckomod/cards", "sneckomodResources", 75),
    "awakened":  ("awakenedOne/cards", "awakenedResources", 70),
}
def strings(res, lang):
    p = R / res / "localization" / lang / "CardStrings.json"
    return json.load(open(p, encoding="utf8")) if p.exists() else {}

def clean(t, vals):
    def ph(m):
        k = m.group(1).lower()
        alias = {"d": "damage", "b": "block", "m": "magicnumber"}
        v = vals.get(alias.get(k, k))
        return str(v) if v is not None else "X"
    t = re.sub(r"!([A-Za-z0-9_:]+)!", ph, t)
    t = re.sub(r"#[ybgrp]", "", t)
    t = re.sub(r"\bNL\b", " ", t)
    t = re.sub(r"\[[^\]]*\]", "", t)
    t = re.sub(r"~|@", "", t)
    return re.sub(r"\s+", " ", t).strip()

rows = []; chars = []
for cid, (cdir, res, hp) in CH.items():
    en = strings(res, "eng")
    n = 0
    for f in sorted((J / cdir).glob("*.java")):
        src = f.read_text(encoding="utf8", errors="ignore")
        m = re.search(r'ID\s*=\s*(?:\w+\.)?makeID\("([^"]+)"\)|ID\s*=\s*"([^"]+)"', src)
        arg = (m.group(1) or m.group(2).split(":")[-1]) if m else f.stem
        key = next((k for k in en if k.split(":")[-1].lower() == arg.lower()), None) or next((k for k in en if k.split(":")[-1].lower() == f.stem.lower()), None)
        if not key: continue
        consts = {k: v for k, v in re.findall(r"(\w+)\s*=\s*(-?\d+)\s*;", src)}
        def num(x): return consts.get(x, x) if not x.lstrip("-").isdigit() else x
        vals = {}
        for name, v in re.findall(r"\bbase(\w+)\s*=\s*(?:\w+\s*=\s*)*(-?\w+)\s*;", src):
            v = num(v)
            if v.lstrip("-").isdigit(): vals[name.lower()] = int(v)
        rar = re.search(r"CardRarity\.(\w+)", src); typ = re.search(r"CardType\.(\w+)", src)
        if not rar or not typ or typ.group(1) not in ("ATTACK", "SKILL", "POWER"): continue
        cm = re.search(r"super\(\s*ID\s*,\s*(?:[A-Za-z_][\w.]*\s*,\s*[A-Za-z_][\w.]*\s*,\s*)?(\w+)", src)
        cost = num(cm.group(1)) if cm else "1"
        if not str(cost).lstrip("-").isdigit(): cost = "1"
        text = clean(en[key].get("DESCRIPTION", ""), vals)
        rows.append("|".join(["DF", cid, en[key]["NAME"], rar.group(1).title(), typ.group(1).title(), str(cost), text]))
        n += 1
    chars.append((cid, hp))
    print(cid, n, "cards")
rows.sort()
def lit(r): return '        "%s"' % r.replace("\\", "\\\\").replace('"', '\\"')
out = pathlib.Path(__file__).resolve().parent.parent / "src/main/java/com/spiremod/mobs/heroes/DownfallData.java"
out.write_text("""package com.spiremod.mobs.heroes;

/** GENERATED by tools/gen_downfall.py from the Downfall (StS1) mod source. Do not edit by hand. Rows: DF|villain|name|rarity|type|cost|text. */
final class DownfallData {
    private DownfallData() {}
    static final String[] ROWS = {
""" + ",\n".join(lit(r) for r in rows) + "\n    };\n}\n")
print(len(rows), "rows")
